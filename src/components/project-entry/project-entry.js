// Swaps the <div id="projects-mount"> placeholder in index.html for the real
// section. outerHTML (not innerHTML) so the placeholder is REPLACED rather than
// wrapped — the final DOM matches what index.html had before the split.
export function mountProjects() {
  const mount = document.querySelector('#projects-mount');

  // Warn and bail if the project placeholder is missing.
  if (!mount) {
    console.warn('mountProjects: #projects-mount not found in index.html');
    return;
  }

  mount.outerHTML = projectsHTML;
}
